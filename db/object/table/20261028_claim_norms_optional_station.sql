DECLARE
    l_nullable VARCHAR2(1);
BEGIN
    SELECT NULLABLE
      INTO l_nullable
      FROM ALL_TAB_COLUMNS
     WHERE OWNER = 'XX_ETW'
       AND TABLE_NAME = 'XX_RJD_CLAIM_NORMS'
       AND COLUMN_NAME = 'STATION_CODE';

    IF l_nullable = 'N' THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE XX_ETW.XX_RJD_CLAIM_NORMS MODIFY STATION_CODE NULL';
    END IF;
END;
/
