CREATE TABLE XX_ETW.XX_RJD_KPI_PAGE_CFG (
    PAGE_CODE VARCHAR2(100 CHAR) NOT NULL,
    USER_KPI_SUPPORTED CHAR(1) DEFAULT 'N' NOT NULL,
    CREATE_ENABLED CHAR(1) DEFAULT 'N' NOT NULL,
    UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_BY NUMBER,
    CONSTRAINT XX_RJD_KPI_PAGE_CFG_PK PRIMARY KEY (PAGE_CODE),
    CONSTRAINT XX_RJD_KPI_PAGE_CFG_SUPPORTED_CK CHECK (USER_KPI_SUPPORTED IN ('Y', 'N')),
    CONSTRAINT XX_RJD_KPI_PAGE_CFG_ENABLED_CK CHECK (CREATE_ENABLED IN ('Y', 'N'))
);

