-- Пользовательские KPI для страниц подхода и отправления.
ALTER TABLE XX_ETW.XX_RJD_KPI_TBL ADD (
    PAGE_CODE VARCHAR2(30 BYTE),
    OWNER_ID NUMBER,
    IS_SYSTEM CHAR(1 BYTE) DEFAULT 'Y' NOT NULL,
    WHERE_CONFIG CLOB
);

UPDATE XX_ETW.XX_RJD_KPI_TBL
   SET PAGE_CODE = CASE TYPE
                     WHEN 'approach_kpi' THEN 'approach'
                     WHEN 'departue_kpi' THEN 'departure'
                     ELSE NULL
                   END,
       IS_SYSTEM = 'Y';

ALTER TABLE XX_ETW.XX_RJD_KPI_TBL ADD CONSTRAINT XX_RJD_KPI_TBL_PK PRIMARY KEY (ID);

ALTER TABLE XX_ETW.XX_RJD_KPI_TBL ADD CONSTRAINT XX_RJD_KPI_TBL_SYSTEM_CK
    CHECK (IS_SYSTEM IN ('Y', 'N'));

CREATE INDEX XX_ETW.XX_RJD_KPI_TBL_OWNER_IDX
    ON XX_ETW.XX_RJD_KPI_TBL (OWNER_ID, PAGE_CODE, IS_SYSTEM);

DECLARE
    l_start NUMBER;
BEGIN
    SELECT NVL(MAX(ID), 0) + 1 INTO l_start FROM XX_ETW.XX_RJD_KPI_TBL;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE XX_ETW.XX_RJD_KPI_TBL_SEQ START WITH ' || l_start || ' INCREMENT BY 1 NOCACHE';
END;
/

CREATE OR REPLACE TRIGGER XX_ETW.XX_RJD_KPI_TBL_BI
BEFORE INSERT ON XX_ETW.XX_RJD_KPI_TBL
FOR EACH ROW
WHEN (NEW.ID IS NULL)
BEGIN
    SELECT XX_ETW.XX_RJD_KPI_TBL_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL;
END;
/

ALTER TABLE XX_ETW.XX_RJD_KPI_TBL ADD CONSTRAINT XX_RJD_KPI_TBL_OWNER_CK
    CHECK ((IS_SYSTEM = 'Y' AND OWNER_ID IS NULL) OR
           (IS_SYSTEM = 'N' AND OWNER_ID IS NOT NULL AND WHERE_CONFIG IS NOT NULL));

ALTER TABLE XX_ETW.XX_RJD_KPI_TBL ADD CONSTRAINT XX_RJD_KPI_TBL_PAGE_CK
    CHECK (IS_SYSTEM = 'Y' OR PAGE_CODE IN ('approach', 'departure'));

COMMENT ON COLUMN XX_ETW.XX_RJD_KPI_TBL.PAGE_CODE IS
    'Код страницы размещения пользовательского KPI';
COMMENT ON COLUMN XX_ETW.XX_RJD_KPI_TBL.OWNER_ID IS
    'ID пользователя-владельца пользовательского KPI';
COMMENT ON COLUMN XX_ETW.XX_RJD_KPI_TBL.IS_SYSTEM IS
    'Y - системный KPI с условиями в PL/SQL, N - пользовательский KPI';
COMMENT ON COLUMN XX_ETW.XX_RJD_KPI_TBL.WHERE_CONFIG IS
    'JSON-конфигурация условий пользовательского KPI';
