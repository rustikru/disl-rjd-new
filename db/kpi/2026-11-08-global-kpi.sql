-- Общие KPI и персональное скрытие карточек. Скрипт рассчитан на Oracle 11g.
ALTER TABLE XX_ETW.XX_RJD_KPI_TBL ADD (
    VISIBILITY VARCHAR2(10 BYTE) DEFAULT 'PRIVATE' NOT NULL
);

UPDATE XX_ETW.XX_RJD_KPI_TBL
   SET VISIBILITY = 'PRIVATE';

ALTER TABLE XX_ETW.XX_RJD_KPI_TBL ADD CONSTRAINT XX_RJD_KPI_TBL_VISIBILITY_CK
    CHECK (VISIBILITY IN ('PRIVATE', 'GLOBAL'));

ALTER TABLE XX_ETW.XX_RJD_KPI_TBL ADD CONSTRAINT XX_RJD_KPI_TBL_GLOBAL_CK
    CHECK (VISIBILITY = 'PRIVATE' OR IS_SYSTEM = 'N');

COMMENT ON COLUMN XX_ETW.XX_RJD_KPI_TBL.VISIBILITY IS
    'PRIVATE - личный KPI, GLOBAL - общий KPI для всех пользователей';

CREATE TABLE XX_ETW.XX_RJD_KPI_HIDDEN (
    USER_ID    NUMBER NOT NULL,
    KPI_ID     NUMBER NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT XX_RJD_KPI_HIDDEN_PK PRIMARY KEY (USER_ID, KPI_ID),
    CONSTRAINT XX_RJD_KPI_HIDDEN_USER_FK FOREIGN KEY (USER_ID)
        REFERENCES XX_ETW.XX_RJD_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT XX_RJD_KPI_HIDDEN_KPI_FK FOREIGN KEY (KPI_ID)
        REFERENCES XX_ETW.XX_RJD_KPI_TBL (ID) ON DELETE CASCADE
);

CREATE INDEX XX_ETW.XX_RJD_KPI_HIDDEN_KPI_IDX
    ON XX_ETW.XX_RJD_KPI_HIDDEN (KPI_ID);

COMMENT ON TABLE XX_ETW.XX_RJD_KPI_HIDDEN IS
    'Персонально скрытые системные и общие KPI-карточки';
COMMENT ON COLUMN XX_ETW.XX_RJD_KPI_HIDDEN.USER_ID IS
    'Пользователь, скрывший общую KPI-карточку';
COMMENT ON COLUMN XX_ETW.XX_RJD_KPI_HIDDEN.KPI_ID IS
    'Скрытая системная или общая KPI-карточка';
