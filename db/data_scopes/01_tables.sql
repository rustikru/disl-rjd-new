-- Выполнить один раз от имени владельца схемы приложения.
create table xx_rjd_data_scopes (
    id number primary key,
    name varchar2(120 char) not null,
    description varchar2(500 char),
    is_active number(1) default 1 not null,
    start_date date,
    end_date date,
    constraint rjd_scopes_active_ck check (is_active in (0, 1)),
    constraint rjd_scopes_dates_ck check (end_date is null or start_date is null or end_date >= start_date)
);
create unique index rjd_scopes_name_uq on xx_rjd_data_scopes (lower(name));
create sequence xx_rjd_data_scopes_seq;

-- Условия одной строки соединяются AND; разрешающие строки объединяются OR.
create table xx_rjd_data_scope_rules (
    id number generated by default as identity primary key,
    scope_id number not null references xx_rjd_data_scopes(id) on delete cascade,
    organization_id number not null references xx_rjd_organizations(id),
    effect varchar2(5 char) default 'ALLOW' not null,
    cargo_code varchar2(50 char),
    station_code varchar2(20 char),
    car_number varchar2(50 char),
    constraint rjd_scope_effect_ck check (effect in ('ALLOW', 'DENY'))
);
create index rjd_scope_rules_ix on xx_rjd_data_scope_rules(scope_id);

create table xx_rjd_user_data_scopes (
    user_id number not null references xx_rjd_users(id) on delete cascade,
    scope_id number not null references xx_rjd_data_scopes(id) on delete cascade,
    constraint rjd_user_scopes_pk primary key(user_id, scope_id)
);
create index rjd_user_scopes_ix on xx_rjd_user_data_scopes(scope_id);

comment on column xx_rjd_data_scope_rules.cargo_code is 'Код груза; NULL означает любой груз';
comment on column xx_rjd_data_scope_rules.station_code is 'Код станции назначения; NULL означает любую станцию';
comment on column xx_rjd_data_scope_rules.car_number is 'Номер вагона; NULL означает любой вагон';
commit;
