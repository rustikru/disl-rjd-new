CREATE TABLE XX_ETW.XX_RJD_DISLOCATION_ARCHIVE
TABLESPACE USERS
AS
SELECT *
  FROM XX_ETW.XX_DISLOCATION_RJD
 WHERE 1 = 0;

ALTER TABLE XX_ETW.XX_RJD_DISLOCATION_ARCHIVE
    MODIFY (ID NOT NULL, REPORT_DT NOT NULL, ORGANIZATION_ID NOT NULL);

ALTER TABLE XX_ETW.XX_RJD_DISLOCATION_ARCHIVE
    ADD CONSTRAINT PK_XX_RJD_DISL_ARCHIVE PRIMARY KEY (ID);

ALTER TABLE XX_ETW.XX_RJD_DISLOCATION_ARCHIVE
    ADD CONSTRAINT FK_XX_RJD_DISL_ARCHIVE_ORG FOREIGN KEY (ORGANIZATION_ID)
        REFERENCES XX_ETW.XX_RJD_ORGANIZATIONS (ID);

CREATE SEQUENCE XX_ETW.XX_RJD_DISL_ARCHIVE_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

DECLARE
    l_row   XX_ETW.XX_RJD_DISLOCATION_ARCHIVE%ROWTYPE;
BEGIN
    FOR c IN
        (SELECT d.id
           FROM XX_ETW.XX_DISLOCATION_RJD d
          WHERE d.type_reference = 'Отправка'
            AND d.report_dt =
                    (SELECT MAX (d2.report_dt)
                       FROM XX_ETW.XX_DISLOCATION_RJD d2
                      WHERE d2.organization_id = d.organization_id
                        AND d2.type_reference = d.type_reference))
    LOOP
        SELECT *
          INTO l_row
          FROM XX_ETW.XX_DISLOCATION_RJD
         WHERE id = c.id;

        l_row.id := XX_ETW.XX_RJD_DISL_ARCHIVE_SEQ.NEXTVAL;
        INSERT INTO XX_ETW.XX_RJD_DISLOCATION_ARCHIVE VALUES l_row;
    END LOOP;
END;
/

CREATE INDEX XX_ETW.IX_XX_RJD_DISL_ARCHIVE_LAST
    ON XX_ETW.XX_RJD_DISLOCATION_ARCHIVE
       (ORGANIZATION_ID, TYPE_REFERENCE, WAGON_NO, ID);

COMMENT ON TABLE XX_ETW.XX_RJD_DISLOCATION_ARCHIVE IS
    'История изменений движения вагонов из справок РЖД';
