CREATE TABLE XX_ETW.XX_RJD_USER_MAILINGS (
    ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    ORGANIZATION_ID NUMBER NOT NULL,
    NAME VARCHAR2(150 CHAR) NOT NULL,
    RECIPIENTS VARCHAR2(2000 CHAR) NOT NULL,
    SUBJECT VARCHAR2(250 CHAR),
    MESSAGE_BODY VARCHAR2(4000 CHAR),
    FILE_FORMAT VARCHAR2(10 CHAR) DEFAULT 'xlsx' NOT NULL,
    SCHEDULE_TYPE VARCHAR2(10 CHAR) DEFAULT 'daily' NOT NULL,
    SEND_TIME VARCHAR2(5 CHAR) DEFAULT '08:00' NOT NULL,
    WEEK_DAYS VARCHAR2(20 CHAR),
    MONTH_DAY NUMBER(2),
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    LAST_RUN_AT DATE,
    LAST_RUN_STATUS VARCHAR2(20 CHAR),
    LAST_RUN_PATH VARCHAR2(1000 CHAR),
    LAST_RUN_MESSAGE VARCHAR2(1000 CHAR),
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT XX_RJD_USER_MAILINGS_PK PRIMARY KEY (ID),
    CONSTRAINT XX_RJD_USER_MAILINGS_U_FK FOREIGN KEY (USER_ID) REFERENCES XX_ETW.XX_RJD_USERS(ID),
    CONSTRAINT XX_RJD_USER_MAILINGS_O_FK FOREIGN KEY (ORGANIZATION_ID) REFERENCES XX_ETW.XX_RJD_ORGANIZATIONS(ID),
    CONSTRAINT XX_RJD_USER_MAILINGS_F_CK CHECK (FILE_FORMAT = 'xlsx'),
    CONSTRAINT XX_RJD_USER_MAILINGS_T_CK CHECK (SCHEDULE_TYPE IN ('daily', 'weekly', 'monthly')),
    CONSTRAINT XX_RJD_USER_MAILINGS_A_CK CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT XX_RJD_USER_MAILINGS_D_CK CHECK (MONTH_DAY IS NULL OR MONTH_DAY BETWEEN 1 AND 31)
);

CREATE SEQUENCE XX_ETW.XX_RJD_USER_MAILINGS_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE OR REPLACE TRIGGER XX_ETW.TRG_XX_RJD_USER_MAILINGS_ID
BEFORE INSERT ON XX_ETW.XX_RJD_USER_MAILINGS
FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN
        :NEW.ID := XX_ETW.XX_RJD_USER_MAILINGS_SEQ.NEXTVAL;
    END IF;
END;
/

CREATE TABLE XX_ETW.XX_RJD_USER_MAILING_REPORTS (
    ID NUMBER NOT NULL,
    MAILING_ID NUMBER NOT NULL,
    REPORT_CODE VARCHAR2(80 CHAR) NOT NULL,
    POSITION NUMBER(4) DEFAULT 0 NOT NULL,
    FILTERS_JSON VARCHAR2(4000 CHAR),
    CONSTRAINT XX_RJD_USER_MAILING_R_PK PRIMARY KEY (ID),
    CONSTRAINT XX_RJD_USER_MAILING_R_FK FOREIGN KEY (MAILING_ID)
        REFERENCES XX_ETW.XX_RJD_USER_MAILINGS(ID) ON DELETE CASCADE,
    CONSTRAINT XX_RJD_USER_MAILING_R_UK UNIQUE (MAILING_ID, REPORT_CODE)
);

CREATE SEQUENCE XX_ETW.XX_RJD_USER_MAILING_R_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE OR REPLACE TRIGGER XX_ETW.TRG_XX_RJD_USER_MAILING_R_ID
BEFORE INSERT ON XX_ETW.XX_RJD_USER_MAILING_REPORTS
FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN
        :NEW.ID := XX_ETW.XX_RJD_USER_MAILING_R_SEQ.NEXTVAL;
    END IF;
END;
/

CREATE INDEX XX_ETW.XX_RJD_USER_MAILINGS_U_IX
    ON XX_ETW.XX_RJD_USER_MAILINGS (USER_ID, IS_ACTIVE);

CREATE INDEX XX_ETW.XX_RJD_USER_MAILING_R_M_IX
    ON XX_ETW.XX_RJD_USER_MAILING_REPORTS (MAILING_ID, POSITION);

CREATE TABLE XX_ETW.XX_RJD_USER_MAILING_RUNS (
    ID NUMBER NOT NULL,
    MAILING_ID NUMBER NOT NULL,
    STARTED_AT DATE DEFAULT SYSDATE NOT NULL,
    FINISHED_AT DATE,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'running' NOT NULL,
    RUN_MODE VARCHAR2(20 CHAR) NOT NULL,
    RECIPIENTS VARCHAR2(2000 CHAR),
    RESULT_PATH VARCHAR2(1000 CHAR),
    MESSAGE VARCHAR2(1000 CHAR),
    CONSTRAINT XX_RJD_USER_MAILING_RUN_PK PRIMARY KEY (ID),
    CONSTRAINT XX_RJD_USER_MAILING_RUN_FK FOREIGN KEY (MAILING_ID)
        REFERENCES XX_ETW.XX_RJD_USER_MAILINGS(ID) ON DELETE CASCADE,
    CONSTRAINT XX_RJD_USER_MAILING_RUN_S_CK CHECK (STATUS IN ('running', 'success', 'error'))
);

CREATE SEQUENCE XX_ETW.XX_RJD_USER_MAILING_RUN_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE OR REPLACE TRIGGER XX_ETW.TRG_XX_RJD_USER_MAILING_RUN_ID
BEFORE INSERT ON XX_ETW.XX_RJD_USER_MAILING_RUNS
FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN
        :NEW.ID := XX_ETW.XX_RJD_USER_MAILING_RUN_SEQ.NEXTVAL;
    END IF;
END;
/

CREATE INDEX XX_ETW.XX_RJD_USER_MAILING_RUN_M_IX
    ON XX_ETW.XX_RJD_USER_MAILING_RUNS (MAILING_ID, STARTED_AT);
