-- Sequence для записей контроля простоев.
BEGIN
    DECLARE
        l_start NUMBER;
    BEGIN
        SELECT NVL(MAX(ID_CONTROL), 0) + 1 INTO l_start FROM XX_ETW.XX_DISL_IDLE_CONTROL;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE XX_ETW.XX_DISL_IDLE_CONTROL_seq START WITH ' || l_start || ' INCREMENT BY 1 NOCACHE';
    END;
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
/

