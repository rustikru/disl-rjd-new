-- Индивидуальная ширина столбцов в пользовательских настройках таблиц.
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE XX_ETW.XX_RJD_TABLE_LAYOUT_COLUMNS ADD (COLUMN_WIDTH NUMBER(4))';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        ALTER TABLE XX_ETW.XX_RJD_TABLE_LAYOUT_COLUMNS
        ADD CONSTRAINT XX_RJD_TBL_LAYOUT_WIDTH_CK
        CHECK (COLUMN_WIDTH IS NULL OR COLUMN_WIDTH BETWEEN 70 AND 800)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -2264 THEN RAISE; END IF;
END;
/
