CREATE TABLE XX_ETW.XX_RJD_CLAIM_NORMS (
    ID NUMBER NOT NULL,
    ORGANIZATION_ID NUMBER NOT NULL,
    RULE_TYPE VARCHAR2(20 CHAR) NOT NULL,
    RULE_VALUE VARCHAR2(500 CHAR) NOT NULL,
    RULE_KEY VARCHAR2(500 CHAR) NOT NULL,
    FREE_DAYS NUMBER(6) DEFAULT 0 NOT NULL,
    DAILY_RATE NUMBER(14,2) DEFAULT 0 NOT NULL,
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CREATED_BY NUMBER NOT NULL,
    UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_BY NUMBER NOT NULL,
    CONSTRAINT XX_RJD_CLAIM_NORMS_PK PRIMARY KEY (ID),
    CONSTRAINT XX_RJD_CLAIM_NORMS_ORG_FK FOREIGN KEY (ORGANIZATION_ID) REFERENCES XX_ETW.XX_RJD_ORGANIZATIONS(ID),
    CONSTRAINT XX_RJD_CLAIM_NORMS_TYPE_CK CHECK (RULE_TYPE IN ('SHIPPER','OWNER','CARGO','CONSIGNEE','PREV_CARGO','WAGON_TYPE')),
    CONSTRAINT XX_RJD_CLAIM_NORMS_DAYS_CK CHECK (FREE_DAYS >= 0),
    CONSTRAINT XX_RJD_CLAIM_NORMS_RATE_CK CHECK (DAILY_RATE >= 0),
    CONSTRAINT XX_RJD_CLAIM_NORMS_DATE_CK CHECK (VALID_TO IS NULL OR VALID_TO >= VALID_FROM)
);

CREATE SEQUENCE XX_ETW.XX_RJD_CLAIM_NORMS_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE OR REPLACE TRIGGER XX_ETW.TRG_XX_RJD_CLAIM_NORMS_ID
BEFORE INSERT ON XX_ETW.XX_RJD_CLAIM_NORMS
FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN
        :NEW.ID := XX_ETW.XX_RJD_CLAIM_NORMS_SEQ.NEXTVAL;
    END IF;
END;
/

CREATE INDEX XX_ETW.XX_RJD_CLAIM_NORMS_ORG_IX ON XX_ETW.XX_RJD_CLAIM_NORMS (ORGANIZATION_ID, RULE_TYPE);
