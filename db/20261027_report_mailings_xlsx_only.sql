-- Переводит существующие задания рассылки на единственный формат Excel.

UPDATE XX_ETW.XX_RJD_USER_MAILINGS
   SET FILE_FORMAT = 'xlsx'
 WHERE FILE_FORMAT <> 'xlsx' OR FILE_FORMAT IS NULL;

ALTER TABLE XX_ETW.XX_RJD_USER_MAILINGS
    DROP CONSTRAINT XX_RJD_USER_MAILINGS_F_CK;

ALTER TABLE XX_ETW.XX_RJD_USER_MAILINGS
    ADD CONSTRAINT XX_RJD_USER_MAILINGS_F_CK CHECK (FILE_FORMAT = 'xlsx');

COMMIT;
