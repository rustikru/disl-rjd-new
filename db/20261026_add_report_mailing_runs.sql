-- Добавляет журнал запусков, если основные таблицы рассылок уже созданы.

CREATE TABLE XX_ETW.XX_RJD_USER_MAILING_RUNS (
    ID NUMBER NOT NULL,
    MAILING_ID NUMBER NOT NULL,
    STARTED_AT DATE DEFAULT SYSDATE NOT NULL,
    FINISHED_AT DATE,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'running' NOT NULL,
    RUN_MODE VARCHAR2(20 CHAR) NOT NULL,
    RECIPIENTS VARCHAR2(2000 CHAR),
    RESULT_PATH VARCHAR2(1000 CHAR),
    MESSAGE VARCHAR2(1000 CHAR),
    CONSTRAINT XX_RJD_USER_MAILING_RUN_PK PRIMARY KEY (ID),
    CONSTRAINT XX_RJD_USER_MAILING_RUN_FK FOREIGN KEY (MAILING_ID)
        REFERENCES XX_ETW.XX_RJD_USER_MAILINGS(ID) ON DELETE CASCADE,
    CONSTRAINT XX_RJD_USER_MAILING_RUN_S_CK CHECK (STATUS IN ('running', 'success', 'error'))
);

CREATE SEQUENCE XX_ETW.XX_RJD_USER_MAILING_RUN_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE OR REPLACE TRIGGER XX_ETW.TRG_XX_RJD_USER_MAILING_RUN_ID
BEFORE INSERT ON XX_ETW.XX_RJD_USER_MAILING_RUNS
FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN
        :NEW.ID := XX_ETW.XX_RJD_USER_MAILING_RUN_SEQ.NEXTVAL;
    END IF;
END;
/

CREATE INDEX XX_ETW.XX_RJD_USER_MAILING_RUN_M_IX
    ON XX_ETW.XX_RJD_USER_MAILING_RUNS (MAILING_ID, STARTED_AT);
