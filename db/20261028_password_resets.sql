CREATE TABLE XX_ETW.XX_RJD_PASSWORD_RESETS (
    ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    TOKEN_HASH VARCHAR2(64 CHAR) NOT NULL,
    EXPIRES_AT DATE NOT NULL,
    USED_AT DATE,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    REQUEST_IP VARCHAR2(45 CHAR),
    CONSTRAINT XX_RJD_PASSWORD_RESETS_PK PRIMARY KEY (ID),
    CONSTRAINT XX_RJD_PASSWORD_RESETS_U_FK FOREIGN KEY (USER_ID)
        REFERENCES XX_ETW.XX_RJD_USERS(ID) ON DELETE CASCADE,
    CONSTRAINT XX_RJD_PASSWORD_RESETS_T_UK UNIQUE (TOKEN_HASH)
);

CREATE SEQUENCE XX_ETW.XX_RJD_PASSWORD_RESETS_SEQ
    START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE OR REPLACE TRIGGER XX_ETW.TRG_XX_RJD_PASSWORD_RESETS
BEFORE INSERT ON XX_ETW.XX_RJD_PASSWORD_RESETS
FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN
        :NEW.ID := XX_ETW.XX_RJD_PASSWORD_RESETS_SEQ.NEXTVAL;
    END IF;
END;
/

CREATE INDEX XX_ETW.XX_RJD_PASSWORD_RESETS_U_IX
    ON XX_ETW.XX_RJD_PASSWORD_RESETS (USER_ID, CREATED_AT);

CREATE INDEX XX_ETW.XX_RJD_PASSWORD_RESETS_E_IX
    ON XX_ETW.XX_RJD_PASSWORD_RESETS (EXPIRES_AT, USED_AT);

